// Builds the stylesheet for fonts uploaded in the CMS. Every value is checked again here,
// so nothing unsafe can reach the CSS even if a content file was edited by hand.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { FONT_CHOICES, FONT_DEFAULT, FONT_KINDS, MAX_CUSTOM_FONTS, fontFileError, fontNameError } from "../lib/fonts.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const FORMATS = { woff2: "woff2", ttf: "truetype", otf: "opentype" };
const { customFonts = [] } = JSON.parse(readFileSync(path.join(ROOT, "content/site/settings.json"), "utf8"));

if (customFonts.length > MAX_CUSTOM_FONTS) throw new Error(`fonts: more than ${MAX_CUSTOM_FONTS} uploaded fonts`);

let css = "/* Generated by scripts/fonts.mjs */\n";
for (const { name, file } of customFonts) {
  const problem = fontNameError(name) ?? fontFileError(file);
  if (problem || FONT_CHOICES.includes(name) || name === FONT_DEFAULT) throw new Error(`fonts: ${name}: ${problem ?? "name is already used"}`);
  if (!existsSync(path.join(ROOT, "public", file))) throw new Error(`fonts: file not found: ${file}`);
  const family = `"Custom ${name}", Georgia, "Times New Roman", serif`;
  css += `/* font: ${name} */\n@font-face { font-family: "Custom ${name}"; src: url("${file}") format("${FORMATS[file.split(".").pop()]}"); font-weight: 100 900; font-style: normal; font-display: swap; }\n`;
  for (const kind of Object.keys(FONT_KINDS)) css += `html[data-font-${kind}="${name}"] { --f-${kind}: ${family}; }\n`;
  css += `[data-font="${name}"] { font-family: ${family} !important; }\n`;
}
writeFileSync(path.join(ROOT, "public/css/custom-fonts.css"), css);
console.log(`fonts: ${customFonts.length} uploaded fonts ready`);
